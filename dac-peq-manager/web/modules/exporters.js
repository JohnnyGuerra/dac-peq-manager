/**
 * Host DSP Configuration Exporters (PipeWire filter-chain, EqualizerAPO, Wavelet GraphicEQ).
 * Mathematically synchronized with Python `src/dac_peq/exporters.py`.
 */

import { computeCompositeCurve, generateLogFrequencies } from "./biquad_math.js";

export function formatPipeWireConf(preset, bands, isFull = false, sinkTarget = "alsa_output.usb-Conexant_CX31993*") {
  const slug = (preset.slug || preset.name || "custom").toLowerCase().replace(/[^a-z0-9]+/g, "_");
  const numBands = bands.length;
  const preampDb = Number(preset.preamp ?? 0.0);
  const linear = Math.pow(10.0, preampDb / 20.0).toFixed(4);
  const typeMap = {
    PK: "bq_peaking",
    PEAK: "bq_peaking",
    PEAKING: "bq_peaking",
    LSQ: "bq_lowshelf",
    LOW_SHELF: "bq_lowshelf",
    LOWSHELF: "bq_lowshelf",
    HSQ: "bq_highshelf",
    HIGH_SHELF: "bq_highshelf",
    HIGHSHELF: "bq_highshelf",
  };

  let nodes = `                    # Preamp Gain Stage (${preampDb > 0 ? "+" : ""}${preampDb.toFixed(1)} dB)
                    { type = builtin, name = "preamp_fl", label = linear, control = { "Gain" = ${linear} } }
                    { type = builtin, name = "preamp_fr", label = linear, control = { "Gain" = ${linear} } }\n`;

  bands.forEach((b, i) => {
    const idx = i + 1;
    const label = typeMap[String(b.type || "PK").toUpperCase()] || "bq_peaking";
    const freq = Number(b.freq ?? 1000.0);
    const gain = Number(b.gain ?? 0.0);
    const q = Number(b.q ?? 1.0);
    nodes += `                    # Band ${idx}: ${b.type} ${freq}Hz ${gain}dB Q=${q}
                    { type = builtin, name = "eq_band${idx}_fl", label = ${label}, control = { "Freq" = ${freq.toFixed(1)}, "Gain" = ${gain.toFixed(2)}, "Q" = ${q.toFixed(2)} } }
                    { type = builtin, name = "eq_band${idx}_fr", label = ${label}, control = { "Freq" = ${freq.toFixed(1)}, "Gain" = ${gain.toFixed(2)}, "Q" = ${q.toFixed(2)} } }\n`;
  });

  let links = `                    { output = "preamp_fl:Out", input = "eq_band1_fl:In" }
                    { output = "preamp_fr:Out", input = "eq_band1_fr:In" }\n`;

  for (let i = 1; i < numBands; i++) {
    links += `                    { output = "eq_band${i}_fl:Out", input = "eq_band${i + 1}_fl:In" }
                    { output = "eq_band${i}_fr:Out", input = "eq_band${i + 1}_fr:In" }\n`;
  }

  return `# PipeWire filter-chain configuration for JCALLY JM6 Pro (Conexant CX31993)
# Preset: ${preset.name} (${numBands} Bands - ${isFull ? "Target Fidelity" : "Hardware Matches"})
# Generated by dac-peq-manager

context.modules = [
    {
        name = libpipewire-module-filter-chain
        args = {
            node.description = "JCALLY JM6 Pro DSP [${preset.name}]"
            media.name       = "JCALLY JM6 Pro DSP [${preset.name}]"
            filter.graph = {
                nodes = [
${nodes}                ]
                links = [
${links}                ]
                inputs  = [ "preamp_fl:In", "preamp_fr:In" ]
                outputs = [ "eq_band${numBands}_fl:Out", "eq_band${numBands}_fr:Out" ]
            }
            capture.props = {
                node.name        = "effect_input.jm6pro_${slug}"
                media.class      = "Audio/Sink"
                audio.position   = [ "FL", "FR" ]
            }
            playback.props = {
                node.name        = "effect_output.jm6pro_${slug}"
                node.target      = "${sinkTarget}"
                audio.position   = [ "FL", "FR" ]
                node.passive     = true
            }
        }
    }
]
`;
}

export function formatEqualizerApo(preset, bands, isFull = false) {
  const preampDb = Number(preset.preamp ?? 0.0);
  let txt = `# EqualizerAPO Configuration\n# Preset: ${preset.name} (${bands.length} Bands - ${isFull ? "Target Fidelity" : "Hardware Matches"})\n\nPreamp: ${preampDb > 0 ? "+" : ""}${preampDb.toFixed(1)} dB\n`;
  bands.forEach((b, i) => {
    const freq = Number(b.freq ?? 1000.0);
    const gain = Number(b.gain ?? 0.0);
    const q = Number(b.q ?? 1.0);
    txt += `Filter ${i + 1}: ON ${b.type} Fc ${freq.toFixed(1)} Hz Gain ${gain >= 0 ? "+" : ""}${gain.toFixed(1)} dB Q ${q.toFixed(2)}\n`;
  });
  return txt;
}

export function formatWaveletGraphicEq(bands, preampDb, points = 127) {
  const frequencies = generateLogFrequencies(points, 20.0, 20000.0);
  const curve = computeCompositeCurve(bands, preampDb, frequencies);
  const pairs = frequencies.map((f, i) => `${Math.round(f)} ${curve[i].toFixed(1)}`);
  return "GraphicEQ: " + pairs.join("; ") + "\n";
}
