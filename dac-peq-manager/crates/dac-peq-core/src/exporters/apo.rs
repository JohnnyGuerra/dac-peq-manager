use crate::models::{FilterType, PeqPreset};

pub fn format_equalizer_apo(preset: &PeqPreset) -> String {
    let mut lines = Vec::new();
    lines.push("# EqualizerAPO Configuration generated by dac-peq-manager".to_string());
    lines.push(format!("# Preset: {}", preset.name));
    if let Some(desc) = &preset.description {
        lines.push(format!("# Description: {desc}"));
    }
    lines.push(format!("Preamp: {:+.1} dB", preset.preamp));

    for (i, b) in preset.bands.iter().enumerate() {
        let apo_type = match b.filter_type {
            FilterType::Peaking => "PK",
            FilterType::LowShelf => "LSC",
            FilterType::HighShelf => "HSC",
            FilterType::Bypass => "PK",
        };
        lines.push(format!(
            "Filter {}: ON {} Fc {:.1} Hz Gain {:+.1} dB Q {:.2}",
            i + 1,
            apo_type,
            b.freq,
            b.gain,
            b.q
        ));
    }

    lines.join("\n") + "\n"
}
