use crate::error::{DacError, Result};
use crate::models::{FilterType, PeqPreset};

pub const DEFAULT_CX31993_SINK: &str = "alsa_output.usb-Conexant_CX31993*";

pub fn format_pipewire_filter_chain(
    preset: &PeqPreset,
    sink_target: &str,
) -> Result<String> {
    if preset.bands.is_empty() {
        return Err(DacError::InvalidFilter("Preset must contain at least 1 band".into()));
    }

    let preset_slug = preset.name.replace([' ', '-'], "_").to_lowercase();
    let description = preset
        .description
        .clone()
        .unwrap_or_else(|| format!("JM6 Pro EQ Preset {}", preset.name));
    let linear_gain = (10.0f64.powf(preset.preamp / 20.0) * 10000.0).round() / 10000.0;
    let num_bands = preset.bands.len();

    let mut nodes = Vec::new();

    // 1. Preamp nodes
    nodes.push(format!(
        r#"                    # Preamp Gain Stage ({:+.1} dB = linear {})
                    {{
                        type   = builtin
                        name   = "preamp_fl"
                        label  = linear
                        control = {{
                            "Gain" = {}
                        }}
                    }}
                    {{
                        type   = builtin
                        name   = "preamp_fr"
                        label  = linear
                        control = {{
                            "Gain" = {}
                        }}
                    }}"#,
        preset.preamp, linear_gain, linear_gain, linear_gain
    ));

    // 2. Band nodes
    for (i, b) in preset.bands.iter().enumerate() {
        let b_idx = i + 1;
        let label = match b.filter_type {
            FilterType::Peaking => "bq_peaking",
            FilterType::LowShelf => "bq_lowshelf",
            FilterType::HighShelf => "bq_highshelf",
            FilterType::Bypass => "bq_peaking",
        };

        nodes.push(format!(
            r#"                    # Band {}: {:?} {:.1} Hz, {:+.1} dB, Q={:.2}
                    {{
                        type   = builtin
                        name   = "eq_band{}_fl"
                        label  = {}
                        control = {{
                            "Freq" = {:.1}
                            "Gain" = {:+.1}
                            "Q"    = {:.2}
                        }}
                    }}
                    {{
                        type   = builtin
                        name   = "eq_band{}_fr"
                        label  = {}
                        control = {{
                            "Freq" = {:.1}
                            "Gain" = {:+.1}
                            "Q"    = {:.2}
                        }}
                    }}"#,
            b_idx, b.filter_type, b.freq, b.gain, b.q,
            b_idx, label, b.freq, b.gain, b.q,
            b_idx, label, b.freq, b.gain, b.q
        ));
    }

    // 3. Chain links
    let mut links = Vec::new();
    links.push(r#"                    { output = "preamp_fl:Out" input = "eq_band1_fl:In" }"#.to_string());
    links.push(r#"                    { output = "preamp_fr:Out" input = "eq_band1_fr:In" }"#.to_string());

    for i in 1..num_bands {
        links.push(format!(
            r#"                    {{ output = "eq_band{}_fl:Out" input = "eq_band{}_fl:In" }}"#,
            i,
            i + 1
        ));
        links.push(format!(
            r#"                    {{ output = "eq_band{}_fr:Out" input = "eq_band{}_fr:In" }}"#,
            i,
            i + 1
        ));
    }

    let nodes_str = nodes.join("\n");
    let links_str = links.join("\n");

    let conf = format!(
        r#"# PipeWire Filter-Chain DSP configuration for {name}
# Generated by dac-peq-manager (Rust Core)
# Target sink: {sink_target}

context.modules = [
    {{
        name = libpipewire-module-filter-chain
        args = {{
            node.description = "{description}"
            media.name       = "{name} DSP"
            filter.graph = {{
                nodes = [
{nodes_str}
                ]
                links = [
{links_str}
                ]
                inputs  = [ "preamp_fl:In" "preamp_fr:In" ]
                outputs = [ "eq_band{num_bands}_fl:Out" "eq_band{num_bands}_fr:Out" ]
            }}
            capture.props = {{
                node.name        = "effect_input.jm6pro_{preset_slug}"
                media.class      = Audio/Sink
                audio.channels   = 2
                audio.position   = [ FL FR ]
            }}
            playback.props = {{
                node.name        = "effect_output.jm6pro_{preset_slug}"
                node.passive     = true
                audio.channels   = 2
                audio.position   = [ FL FR ]
                target.object    = "{sink_target}"
            }}
        }}
    }}
]
"#,
        name = preset.name,
        sink_target = sink_target,
        description = description,
        nodes_str = nodes_str,
        links_str = links_str,
        num_bands = num_bands,
        preset_slug = preset_slug
    );

    Ok(conf)
}
